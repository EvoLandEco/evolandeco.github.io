  help: [arrow + badgeLines("M22 22C22 19 27 19 27 22Q27 24 24 24V25M24 28H24.1"), 6, 4],
  "context-menu": [arrow + badgeLines("M21 21H27M21 24H27M21 27H25"), 6, 4],
