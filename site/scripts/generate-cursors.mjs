const arrow = outline(path("M6 4 22 17Q23 18.5 21 18.2L15 17.5Q14 17.4 13.6 18.5L11.5 24.5Q10.8 26 10.4 24.3L5.6 5Q5.3 3.4 6 4Z"), blue);
