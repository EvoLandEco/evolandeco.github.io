const path = d => `<path d="${d}"/>`;
const circle = (x, y, r) => `<circle cx="${x}" cy="${y}" r="${r}"/>`;
const outline = (shape, color = neon) => `<g fill="none" stroke-linecap="round" stroke-linejoin="round"><g stroke="${color}" stroke-width="5.5" opacity=".24">${shape}</g><g stroke="${ink}" stroke-width="3.3" opacity=".85">${shape}</g><g stroke="${color}" stroke-width="1.9">${shape}</g></g>`;
