  wait: [wait, 16, 16],
  alias: [arrow + badgeLines("M21 27V23H27M24 20 27 23 24 26"), 6, 4],
  copy: [arrow + badgeLines("M20 24H28M24 20V28"), 6, 4],
  move: [move, 16, 16],
  "all-scroll": [move, 16, 16],
  "not-allowed": [blocked, 16, 16],
  "no-drop": [arrow + outline(circle(24, 24, 5)) + badgeLines("M21 21 27 27"), 6, 4],
  grab: [grip(false), 16, 16],
  grabbing: [grip(true), 16, 16],
  "zoom-in": [zoom(true), 13, 13],
  "zoom-out": [zoom(false), 13, 13],
  "ew-resize": [resize(0), 16, 16],
