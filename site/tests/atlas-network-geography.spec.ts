test("Geographic highlights preserve topology and follow the shared transition positions", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ reducedMotion: "no-preference" });
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/atlas/");
  await expect(page.locator(".atlas-page")).toHaveAttribute("data-ready", "true");
  await page.getByRole("button", { name: "Click to enter full screen" }).click();
  await expect(page.locator("html")).not.toHaveAttribute("data-atlas-workspace-transition");
  const globe = page.getByTestId("atlas-globe"), canvas = globe.locator("canvas").first();
  await page.getByRole("radio", { name: "Network view" }).click();
  const frames = await globe.evaluate(element => new Promise<{ mix: number; attached: boolean }[]>(resolve => {
    const frames: { mix: number; attached: boolean }[] = [];
    const sample = () => {
      const mix = Number(element.querySelector("canvas")?.dataset.networkMix);
      const members = [...element.querySelectorAll('.globe-geography-member')];
      const pins = [...element.querySelectorAll('.atlas-globe-pin')];
      frames.push({ mix, attached: members.every((member, i) => member.getAttribute('transform') === pins[i]?.getAttribute('transform')) });
      if (mix === 1) resolve(frames); else requestAnimationFrame(sample);
    }; sample();
  }));
  expect(frames.some(frame => frame.mix > 0 && frame.mix < 1)).toBe(true);
  expect(frames.filter(frame => frame.mix > 0).every(frame => frame.attached)).toBe(true);
  const positions = () => globe.locator('.atlas-globe-pin').evaluateAll(pins => pins.map(pin => pin.getAttribute('transform')));
  const before = await positions(), bounds = await canvas.boundingBox();
  const europe = page.getByRole("button", { name: "Highlight Europe", exact: true });
  const asia = page.getByRole("button", { name: "Highlight Asia", exact: true });
  await europe.click();
  await asia.press("Space");
  await expect(europe).toHaveAttribute("aria-pressed", "true");
  await expect(asia).toHaveAttribute("aria-pressed", "true");
  const highlightedRegions = () => globe.locator('.globe-continent-envelope[data-active="true"]').evaluateAll(paths => [...new Set(paths.map(path => path.getAttribute('data-region')))].sort());
  expect(await highlightedRegions()).toEqual(["142", "150"]);
  await expect(globe.locator('select')).toHaveCount(0);
  expect(await positions()).toEqual(before);
  expect(await canvas.boundingBox()).toEqual(bounds);
  const keyBounds = await globe.locator('.globe-continent-key').boundingBox();
  const legendBounds = await page.getByRole('list', { name: 'Link types' }).boundingBox();
  expect(keyBounds!.y).toBeGreaterThan(bounds!.y + bounds!.height * .85);
  expect(keyBounds!.y + keyBounds!.height).toBeLessThanOrEqual(legendBounds!.y);
  await europe.press("Enter");
  await expect(europe).toHaveAttribute("aria-pressed", "false");
  await expect(asia).toHaveAttribute("aria-pressed", "true");
  await page.mouse.move(10, 10);
  await asia.focus();
  expect(await highlightedRegions()).toEqual(["142"]);
  await europe.press("Space");
  await page.screenshot({ path: test.info().outputPath("geography-multiselect.png") });
  await europe.press("Escape");
  await expect(europe).toHaveAttribute("aria-pressed", "false");
  await expect(asia).toHaveAttribute("aria-pressed", "false");
  await expect(page.locator('.atlas-page')).toHaveAttribute('data-fullscreen');
  await page.getByRole('radio', { name: 'Map view' }).click();
  await expect(canvas).toHaveAttribute('data-network-mix', '0.0000');
  await expect(page.getByRole('button', { name: 'Highlight Europe', exact: true })).not.toBeVisible();
  expect(await canvas.boundingBox()).toEqual(bounds);
  expect(errors).toEqual([]);
});

test("The continent selector appears only in fullscreen Network without resizing the globe", async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/atlas/");
  await expect(page.locator(".atlas-page")).toHaveAttribute("data-ready", "true");
  await page.getByRole('radio', { name: 'Network view' }).press('Enter');
  const key = page.getByRole('group', { name: 'Highlight geographic groups' });
  await expect(key).not.toBeVisible();
  await page.getByRole("button", { name: "Click to enter full screen" }).click();
  await expect(page.locator("html")).not.toHaveAttribute("data-atlas-workspace-transition");
  await expect(key).toBeVisible();
  const globe = page.getByTestId('atlas-globe'), canvas = globe.locator('canvas').first();
  const bounds = await canvas.boundingBox();
  await page.getByRole('button', { name: 'Highlight Asia', exact: true }).press('Enter');
  await page.getByRole('button', { name: 'Highlight Europe', exact: true }).press('Space');
  expect(await canvas.boundingBox()).toEqual(bounds);
  await page.getByRole('switch', { name: 'Dark mode' }).click();
  await expect(page.locator('html')).toHaveClass(/dark/);
  await page.getByRole('radio', { name: 'Map view' }).press('Enter');
  await expect(key).not.toBeVisible();
  expect(await canvas.boundingBox()).toEqual(bounds);
  await page.getByRole('radio', { name: 'Network view' }).press('Enter');
  await expect(key).toBeVisible();
  await expect(page.getByRole('button', { name: 'Highlight Asia', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByRole('button', { name: 'Highlight Europe', exact: true })).toHaveAttribute('aria-pressed', 'true');
  expect(await canvas.boundingBox()).toEqual(bounds);
  await page.screenshot({ path: test.info().outputPath('geography-fullscreen-dark.png') });
  await page.getByRole('button', { name: /Exit full screen/ }).click();
  await expect(key).not.toBeVisible();
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await globe.scrollIntoViewIfNeeded();
    await expect(key).not.toBeVisible();
    await expect(globe.locator('select')).toHaveCount(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  }
});

test("Continent hover previews nodes and envelopes while preserving multiple selections", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto('/atlas/');
  await expect(page.locator('.atlas-page')).toHaveAttribute('data-ready', 'true');
  await page.getByRole('button', { name: 'Click to enter full screen' }).click();
  await page.getByRole('radio', { name: 'Network view' }).click();
  const globe = page.getByTestId('atlas-globe');
  const asia = page.getByRole('button', { name: 'Highlight Asia', exact: true });
  const europe = page.getByRole('button', { name: 'Highlight Europe', exact: true });
  const africa = page.getByRole('button', { name: 'Highlight Africa', exact: true });
  const highlightedRegions = () => globe.locator('.globe-continent-envelope[data-active="true"]').evaluateAll(paths => [...new Set(paths.map(path => path.getAttribute('data-region')))].sort());
  const ringVisibility = () => globe.locator('.globe-geography-member').evaluateAll(members => members.map(member => ({
    active: member.getAttribute('data-active') === 'true', opacity: Number(getComputedStyle(member).opacity),
  })));
  expect((await ringVisibility()).every(ring => !ring.active && ring.opacity === 0)).toBe(true);
  await expect(globe.locator('.atlas-globe-pin[data-network-isolated="true"]')).not.toHaveCount(0);
  await asia.hover();
  expect(await highlightedRegions()).toEqual(['142']);
  await expect(asia).toHaveAttribute('aria-pressed', 'false');
  await expect(globe.locator('.globe-geography-member[data-countries~="CN"][data-active="true"]')).not.toHaveCount(0);
  await expect(globe.locator('.globe-country-envelope[data-country="CN"][data-active="true"]')).not.toHaveCount(0);
  const previewRings = await ringVisibility();
  expect(previewRings.some(ring => ring.active && ring.opacity === 1)).toBe(true);
  expect(previewRings.every(ring => ring.opacity === Number(ring.active))).toBe(true);
  await page.mouse.move(10, 10);
  expect(await highlightedRegions()).toEqual([]);
  expect((await ringVisibility()).every(ring => ring.opacity === 0)).toBe(true);
  await page.screenshot({ path: test.info().outputPath('network-without-geographic-rings.png') });
  await asia.click();
  await europe.click();
  await africa.hover();
  expect(await highlightedRegions()).toEqual(['002', '142', '150']);
  await expect(africa).toHaveAttribute('aria-pressed', 'false');
  await expect(asia).toHaveAttribute('aria-pressed', 'true');
  await expect(europe).toHaveAttribute('aria-pressed', 'true');
  await page.screenshot({ path: test.info().outputPath('geography-hover-preview.png') });
  await page.mouse.move(10, 10);
  expect(await highlightedRegions()).toEqual(['142', '150']);
  await europe.click();
  await page.mouse.move(10, 10);
  expect(await highlightedRegions()).toEqual(['142']);
  await asia.focus();
  await asia.press('Tab');
  await expect(europe).toBeFocused();
  await expect(europe).toHaveAttribute('aria-pressed', 'false');
  expect(await highlightedRegions()).toEqual(['142', '150']);
  await europe.press('Escape');
  expect(await highlightedRegions()).toEqual([]);
  const nodeIndex = await globe.locator('.globe-geography-member').evaluateAll(nodes => nodes.findIndex(node => node.getAttribute('data-countries')?.split(' ').includes('NL')));
  await globe.locator('.atlas-globe-pin').nth(nodeIndex).focus();
  await expect(globe.locator('.globe-country-envelope[data-country="NL"][data-active="true"]')).not.toHaveCount(0);
  expect((await ringVisibility()).every(ring => ring.opacity === 0)).toBe(true);
  await asia.hover();
  expect(await highlightedRegions()).toEqual(['142']);
});

test("View reset clears continent selections without moving the network or changing reporting dates", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.goto('/atlas/');
  await expect(page.locator('.atlas-page')).toHaveAttribute('data-ready', 'true');
  await page.getByRole('button', { name: 'Click to enter full screen' }).click();
  await expect(page.locator('html')).not.toHaveAttribute('data-atlas-workspace-transition');
  await page.getByRole('radio', { name: 'Network view' }).click();
  const globe = page.getByTestId('atlas-globe'), canvas = globe.locator('canvas').first();
  await expect(canvas).toHaveAttribute('data-network-mix', '1.0000');
  const reset = page.getByRole('button', { name: 'Clear continent selection', exact: true });
  const asia = page.getByRole('button', { name: 'Highlight Asia', exact: true });
  const europe = page.getByRole('button', { name: 'Highlight Europe', exact: true });
  const state = () => page.locator('.atlas-page').evaluate(element => ({
    positions: [...element.querySelectorAll('.atlas-globe-pin')].map(pin => pin.getAttribute('transform')),
    dates: [...element.querySelectorAll<HTMLInputElement>('.atlas-ranges input')].map(input => input.value),
  }));
  const before = await state(), bounds = await canvas.boundingBox(), resetBounds = await reset.boundingBox();
  await expect(reset).toHaveAttribute('aria-disabled', 'true');
  await asia.hover();
  await expect(reset).toHaveAttribute('aria-disabled', 'true');
  await asia.click();
  await europe.click();
  await expect(asia).toHaveAttribute('aria-pressed', 'true');
  await expect(europe).toHaveAttribute('aria-pressed', 'true');
  await expect(reset).toHaveAttribute('aria-disabled', 'false');
  await reset.click();
  await expect(asia).toHaveAttribute('aria-pressed', 'false');
  await expect(europe).toHaveAttribute('aria-pressed', 'false');
  await expect(reset).toHaveAttribute('aria-disabled', 'true');
  await expect(globe.locator('.globe-continent-envelope[data-active="true"]')).toHaveCount(0);
  await expect(globe.locator('.globe-geography-member[data-active="true"]')).toHaveCount(0);
  expect(await state()).toEqual(before);
  expect(await canvas.boundingBox()).toEqual(bounds);
  expect(await reset.boundingBox()).toEqual(resetBounds);
  await asia.press('Space');
  await reset.press('Enter');
  await expect(asia).toHaveAttribute('aria-pressed', 'false');
  await expect(reset).toHaveAttribute('aria-disabled', 'true');
  await page.getByRole('radio', { name: 'Map view' }).click();
  await expect(page.getByRole('button', { name: 'Reset globe tilt', exact: true })).toHaveAttribute('aria-disabled', 'true');
  await page.getByRole('radio', { name: 'Network view' }).click();
  await expect(canvas).toHaveAttribute('data-network-mix', '1.0000');
  await expect(asia).toHaveAttribute('aria-pressed', 'false');
  await expect(reset).toHaveAttribute('aria-disabled', 'true');
});
