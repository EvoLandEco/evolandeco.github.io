import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { routeBrowserFixture } from './atlas-browser-fixture.mjs';
import { bundle } from './atlas-fixture';
import { releaseSchema } from '../src/lib/atlas-release';
import { dailyFixture, dailyPointer } from './atlas-daily-fixture';
import type { DailyData } from '../src/lib/atlas-vendor/daily/0.2.3/daily';

for (const width of [390, 1466]) test(`Historical publication bindings preserve counts, pending captures and report navigation at ${width}px`, async ({ page }) => {
  const fixture = await routeBrowserFixture(page, bundle, JSON.parse(readFileSync('.cache/atlas-fixture/map.json', 'utf8')));
  const manifest = JSON.parse(fixture.bodies[`/releases/${fixture.release.export_id}/browser/${fixture.release.browser.manifest.sha256}/manifest.json`].toString());
  const data: DailyData = { ...dailyFixture(releaseSchema.parse(fixture.release), manifest.source.manifest.sha256), daily_version: '0.2.3', publication_bindings: [] };
  const versions = bundle.documents.filter(document => document.channel_id === 'who-don').sort((a, b) => b.publication.localeCompare(a.publication)).slice(0, 3);
  expect(versions).toHaveLength(3);
  data.documents[0].base_document_ids = versions.slice(0, 2).map(document => document.id);
  data.documents[1].base_document_ids = [versions[2].id];
  await page.route(/\/daily\//, route => route.fulfill({ contentType: 'application/json', body: JSON.stringify(route.request().url().endsWith('current.json') ? dailyPointer(data) : data) }));
  await page.setViewportSize({ width, height: 832 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/atlas/');
  await expect(page.locator('.atlas-daily-watch')).toBeVisible();
  const unboundCount = Number.parseInt(await page.locator('.atlas-trend-activity header strong').innerText(), 10);
  data.publication_bindings = [{ document_versions: versions.map(document => ({ document_id: document.id, raw_sha256: document.raw_sha256, source_text_sha256: document.text_sha256 })), assertion_ids: ['fixture-assertion'], comparison_ids: ['fixture-comparison'], evidence_ids: ['fixture-evidence'], reason: 'Synthetic publisher versions reviewed for interface testing.', reviewed_at: data.generated_at, reviewed_by: 'fixture' }];
  await page.reload();
  await expect(page.locator('.atlas-daily-watch')).toBeVisible();
  await expect(page.locator('.atlas-trend-activity header strong')).toHaveText(`${unboundCount - 1} reports`);
  await page.locator('.atlas-daily-watch').getByRole('button', { name: 'View reports', exact: true }).click();
  const report = page.locator(`#atlas-report-${versions[0].id}`);
  await expect(report).toHaveAttribute('data-evidence', 'true');
  for (const version of versions.slice(1)) await expect(page.locator(`#atlas-report-${version.id}`)).toHaveCount(0);
  await report.locator(':scope > summary').click();
  await expect(report.locator('.atlas-daily-version')).toHaveCount(1);
  await expect(report.locator('.atlas-daily-processing')).toHaveText('Weekly review pending');
  await report.locator('.atlas-daily-version .atlas-source-versions > summary').click();
  await expect(report.locator('.atlas-daily-version .atlas-source-versions [data-source-version]')).toHaveCount(2);
  await report.locator(':scope > .atlas-report-body > .atlas-source-versions > summary').click();
  await expect(report.locator(':scope > .atlas-report-body > .atlas-source-versions [data-source-version]')).toHaveCount(3);
  await page.getByRole('tab', { name: 'Trends', exact: true }).click();
  await page.locator('summary[aria-label="Reporting source"]').click();
  const menu = page.getByRole('dialog', { name: 'Reporting source', exact: true });
  await menu.getByRole('checkbox', { name: 'Santé publique France', exact: true }).check();
  await menu.getByRole('searchbox').press('Escape');
  await expect(page.locator('.atlas-trend-activity header strong')).toHaveText('1 reports');
  await page.getByRole('tab', { name: 'Reports', exact: true }).click();
  await expect(page.locator('.atlas-daily-report')).toHaveCount(1);
  await page.locator('.atlas-daily-report > summary').click();
  await expect(page.locator('.atlas-daily-report .atlas-daily-version')).toHaveCount(1);
  await page.locator('.atlas-daily-report .atlas-source-versions > summary').click();
  await expect(page.locator('.atlas-daily-report .atlas-source-versions [data-source-version]')).toHaveCount(2);
  for (const version of versions) await expect(page.locator(`[data-source-version="${version.id}"]`)).toHaveCount(0);
});

test('Integrated version bindings share one report body and preserve both source captures', async ({ page }) => {
  const fixture = await routeBrowserFixture(page, bundle, JSON.parse(readFileSync('.cache/atlas-fixture/map.json', 'utf8')));
  const manifest = JSON.parse(fixture.bodies[`/releases/${fixture.release.export_id}/browser/${fixture.release.browser.manifest.sha256}/manifest.json`].toString());
  const data = dailyFixture(releaseSchema.parse(fixture.release), manifest.source.manifest.sha256);
  const [newer, older] = bundle.documents.filter(document => document.channel_id === 'who-don').sort((a, b) => b.publication.localeCompare(a.publication));
  data.documents[0].base_document_ids = [newer.id, older.id];
  data.reconciliations.push({ review_id: data.documents[0].review_id!, weekly_export_id: fixture.release.export_id, record_ids: newer.record_ids, disposition: 'integrated', reason: 'Integrated source review.', reviewed_at: data.knowledge_cutoff, reviewed_by: 'fixture', weekly_inbox_sha256: 'c'.repeat(64) });
  await page.route(/\/daily\//, route => route.fulfill({ contentType: 'application/json', body: JSON.stringify(route.request().url().endsWith('current.json') ? dailyPointer(data) : data) }));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/atlas/');
  await expect(page.locator('.atlas-daily-watch')).toBeVisible();
  await expect(page.locator(`[data-report-id="${newer.id}"]`)).toHaveCount(1);
  await expect(page.locator(`[data-report-id="${older.id}"]`)).toHaveCount(0);
  await page.locator('.atlas-daily-watch').getByRole('button', { name: 'View reports', exact: true }).click();
  const report = page.locator(`#atlas-report-${newer.id}`);
  await expect(report).toHaveAttribute('data-evidence', 'true');
  await expect(page.locator(`#atlas-report-${older.id}`)).toHaveCount(0);
  await expect(report.locator('.atlas-daily-processing')).toHaveCount(0);
  await report.locator(':scope > summary').click();
  await expect(report.locator(':scope > .atlas-report-body')).toHaveCount(1);
  await expect(report.getByRole('link', { name: 'Read source', exact: true })).toHaveCount(1);
  await report.locator('.atlas-source-versions > summary').click();
  const versions = report.locator('.atlas-source-versions [data-source-version]');
  await expect(versions).toHaveCount(2);
  expect(await versions.evaluateAll(links => links.map(link => link.getAttribute('data-source-version')))).toEqual([newer.id, older.id]);
  expect(await versions.evaluateAll(links => links.map(link => link.getAttribute('href')))).toEqual([newer.url, older.url]);
  await expect(report.locator('.atlas-daily-version')).toHaveCount(0);
});

